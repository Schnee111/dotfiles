#!/usr/bin/env bash
# Tests for rices/end4/hypr/scripts/apply_adaptive_glass.sh:
# 1. Blur brightness goes to hyprland/glass.lua (generated state), through the
#    symlink into the repo, for every luminance tier.
# 2. Hand-written custom/general.lua is never touched.
# 3. Without a hyprland/ directory nothing is created.
# 4. Kitty opacity goes to the untracked live wrapper, after its include: appended
#    once, then replaced; a symlinked kitty.conf and solid mode are left alone.
# 5. Window opacity is stored in the shell's config.json too, through a symlink
#    without replacing it; solid mode and a missing config.json are left alone.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
SCRIPT="$REPO/rices/end4/hypr/scripts/apply_adaptive_glass.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

fail() {
    echo "FAIL: $*" >&2
    exit 1
}

# --- Stubs --------------------------------------------------------------------

STUBS="$TMP/bin"
mkdir -p "$STUBS"
# magick prints the luminance the test asks for
cat >"$STUBS/magick" <<'EOF'
#!/usr/bin/env bash
echo "$MOCK_LUM"
EOF
for cmd in hyprctl kitten gsettings python3 pgrep; do
    printf '#!/usr/bin/env bash\nexit 0\n' >"$STUBS/$cmd"
done
chmod +x "$STUBS"/*
export PATH="$STUBS:$PATH"

# --- Fake install: live files are symlinks into a copy of the repo files -------

export HOME="$TMP/home"
SRC="$TMP/src"
mkdir -p "$HOME/.config/hypr/hyprland" "$HOME/.config/hypr/custom" "$SRC"
cp "$REPO/rices/end4/hypr/hyprland/glass.lua" "$SRC/glass.lua"
cp "$REPO/rices/end4/hypr/custom/general.lua" "$SRC/general.lua"
ln -s "$SRC/glass.lua" "$HOME/.config/hypr/hyprland/glass.lua"
ln -s "$SRC/general.lua" "$HOME/.config/hypr/custom/general.lua"
WALLPAPER="$TMP/wall.png"
: >"$WALLPAPER"

run() {
    MOCK_LUM="$1" bash "$SCRIPT" "$WALLPAPER"
}

# --- 1 + 2: every tier ---------------------------------------------------------

for case in "80.5:0.95" "50:1.00" "30:1.08" "10:1.15"; do
    lum="${case%%:*}" want="${case#*:}"
    run "$lum"
    [[ -L "$HOME/.config/hypr/hyprland/glass.lua" ]] || fail "glass.lua symlink was replaced (lum $lum)"
    grep -qxF "hl.config({ decoration = { blur = { brightness = $want } } })" "$SRC/glass.lua" \
        || fail "lum $lum: expected brightness $want, got: $(grep hl.config "$SRC/glass.lua")"
    cmp -s "$SRC/general.lua" "$REPO/rices/end4/hypr/custom/general.lua" \
        || fail "lum $lum: custom/general.lua was modified"
done
echo "ok: brightness written to glass.lua for all tiers, general.lua untouched"

grep -qE 'brightness *=' "$REPO/rices/end4/hypr/custom/general.lua" \
    && fail "custom/general.lua still sets blur brightness"
echo "ok: custom/general.lua no longer sets blur brightness"

# --- 3: no hyprland/ directory -------------------------------------------------

rm -rf "$HOME/.config/hypr/hyprland"
run 50
[[ ! -e "$HOME/.config/hypr/hyprland" ]] || fail "hyprland/ was created"
echo "ok: nothing created without hyprland/"

# --- 4: kitty wrapper ------------------------------------------------------------

KITTY="$HOME/.config/kitty/kitty.conf"
mkdir -p "${KITTY%/*}"
cat >"$KITTY" <<EOF
# Generated by dotfiles install.sh -- edit common/kitty/kitty.conf instead.
# Rice theme generators append includes here; this file is not tracked.
include $REPO/common/kitty/kitty.conf
EOF

run 50
[[ "$(tail -n1 "$KITTY")" == "background_opacity 0.60" ]] || fail "opacity not appended after the include: $(cat "$KITTY")"
run 10
[[ "$(grep -c '^background_opacity ' "$KITTY")" == 1 ]] || fail "opacity line duplicated: $(cat "$KITTY")"
[[ "$(tail -n1 "$KITTY")" == "background_opacity 0.40" ]] || fail "opacity not replaced: $(cat "$KITTY")"
echo "ok: kitty opacity appended once, then replaced"

touch "$HOME/.config/hypr/custom/.solid_mode"
run 80
[[ "$(tail -n1 "$KITTY")" == "background_opacity 0.40" ]] || fail "solid mode still wrote kitty opacity"
rm "$HOME/.config/hypr/custom/.solid_mode"
echo "ok: solid mode leaves kitty.conf alone"

cp "$REPO/common/kitty/kitty.conf" "$SRC/kitty.conf"
ln -sfn "$SRC/kitty.conf" "$KITTY"
run 80
cmp -s "$SRC/kitty.conf" "$REPO/common/kitty/kitty.conf" || fail "symlinked (tracked) kitty.conf was modified"
echo "ok: symlinked kitty.conf left alone"

# --- 5: shell config.json --------------------------------------------------------

SHELL_CONFIG="$HOME/.config/illogical-impulse/config.json"
run 50
[[ ! -e "$SHELL_CONFIG" ]] || fail "config.json was created"

mkdir -p "${SHELL_CONFIG%/*}"
echo '{"bar": {"x": 1}, "hyprland": {"decoration": {"activeOpacity": 0.86, "inactiveOpacity": 0.76, "rounding": 16}}}' \
    >"$SRC/config.json"
ln -s "$SRC/config.json" "$SHELL_CONFIG"
opacity() { jq -c '[.hyprland.decoration.activeOpacity, .hyprland.decoration.inactiveOpacity]' "$SRC/config.json"; }

run 50
[[ "$(opacity)" == "[0.88,0.78]" ]] || fail "lum 50: expected [0.88,0.78], got $(opacity)"
[[ -L "$SHELL_CONFIG" ]] || fail "config.json symlink was replaced"
[[ "$(jq -c '[.bar.x, .hyprland.decoration.rounding]' "$SRC/config.json")" == "[1,16]" ]] \
    || fail "other config.json keys changed: $(cat "$SRC/config.json")"
run 10
[[ "$(opacity)" == "[0.84,0.74]" ]] || fail "lum 10: expected [0.84,0.74], got $(opacity)"
echo "ok: window opacity stored in config.json, symlink and other keys kept"

touch "$HOME/.config/hypr/custom/.solid_mode"
run 80
[[ "$(opacity)" == "[0.84,0.74]" ]] || fail "solid mode still wrote config.json"
rm "$HOME/.config/hypr/custom/.solid_mode"
echo "ok: solid mode leaves config.json alone"

echo '{"hyprland": ' >"$SRC/config.json"
cp "$SRC/config.json" "$TMP/broken.json"
run 50
cmp -s "$SRC/config.json" "$TMP/broken.json" || fail "unparsable config.json was rewritten"
[[ ! -e "$SRC/config.json.tmp" ]] || fail "config.json.tmp left behind"
echo "ok: unparsable config.json left alone"
